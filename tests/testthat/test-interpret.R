test_that("permutation importance uses original grouped columns and reproducible RNG", {
  d <- example_data(100)
  fit <- surv_fit(Surv(time, event) ~ x + z + batch, d)
  set.seed(45)
  before <- .Random.seed
  a <- surv_importance(fit, d, list(numeric = c("x", "z"), category = "batch"), n_repeats = 3, seed = 9)
  expect_identical(.Random.seed, before)
  expect_identical(a, surv_importance(fit, d, list(numeric = c("x", "z"), category = "batch"), n_repeats = 3, seed = 9))
  expect_equal(nrow(attr(a, "permutations")), 6)
  expect_equal(attr(a, "settings")$baseline, surv_score(fit, d))
  expect_error(surv_importance(fit, d, "event"), "predictor")
  expect_error(surv_importance(fit, d, "x", n_repeats = 0), "integer")
  expect_equal(nrow(surv_importance(fit, d, "x", n_repeats = 1)), 1)
})

test_that("ALE matches a linear Cox score and learned transformations", {
  d <- example_data(100)
  fit <- surv_fit(Surv(time, event) ~ x + z, d)
  a <- surv_ale(fit, d[c("x", "z")], "x", bins = 5)
  beta <- unname(stats::coef(fit$engine)[1])
  expect_equal(a$local_difference, beta * (a$upper - a$lower), tolerance = 1e-12)
  expect_equal(sum(a$n * a$ale), 0, tolerance = 1e-12)
  expect_equal(sum(a$n), nrow(d))
  d$x <- exp(d$x)
  fit <- surv_fit(Surv(time, event) ~ log(x) + z, d)
  a <- surv_ale(fit, d, "x", bins = 4)
  expect_equal(a$local_difference, unname(coef(fit$engine)[1]) * log(a$upper / a$lower), tolerance = 1e-12)
  expect_error(surv_ale(fit, d, "batch"), "predictor")
  expect_error(surv_ale(fit, d, "x", type = "risk", time = 3), "only")
})

test_that("ALE handles tied quantiles, probability targets and plotting", {
  d <- example_data(100)
  d$x <- rep(c(0, 0, 0, 0, 1), length.out = nrow(d))
  fit <- surv_fit(Surv(time, event) ~ x + z, d)
  a <- surv_ale(fit, d, "x", bins = 10, type = "failure", time = 3)
  expect_equal(sum(a$n), nrow(d))
  expect_true(all(a$n > 0))
  expect_true(all(is.finite(a$ale)))
  expect_error(surv_ale(fit, d, "x", type = "failure"), "time")
  tree <- surv_fit(Surv(time, event) ~ x + z, d, "tree")
  expect_error(surv_ale(tree, d, "x", type = "failure", time = 3), "native")
  path <- tempfile(fileext = ".pdf")
  grDevices::pdf(path)
  plot(a)
  plot(surv_importance(fit, d, "x", n_repeats = 1))
  grDevices::dev.off()
  expect_true(file.info(path)$size > 100)
  unlink(path)
})
